/** A `RecoveryPublisher` holding checkouts that must be removed once the run has finished with them. */
export interface TaggedCommitPublisher extends RecoveryPublisher {
  /** Removes every checkout `publish` created. */
  close: () => Promise<void>;
}

/** The version every first release is measured from, as semantic-release starts a package's first release from nothing. */
const NO_PREVIOUS_VERSION = '0.0.0';

/**
 * Publishes a tagged release from the commit its tag names, through the package's own configured publish plugins.
 *
 * The tagged commit is checked out into a linked worktree of its own and installed from its committed lockfile, the state the release job that tagged it published from, so the build that `npm publish` runs (`prepack`, `prepublishOnly`) sees exactly the tagged sources; the release checkout itself is never touched. Releases tagged on the same commit, as every release of one `commitStrategy: 'single'` run is, share one checkout and one install.
 *
 * The release context (branch, channel, repository) comes from a dry semantic-release run in the package's own directory, which every real release also starts from, so a release is only republished from a checkout semantic-release itself would release from. Release notes are regenerated by the same path-scoped generator, over the commits between the previous release tag and the release commit the tag points at (the release commit's own parent, since both commit strategies tag the commit that records the release, which the notes were computed before).
 *
 * The plugins then run as semantic-release's own publish pipeline would have: every plugin's `verifyConditions`, then the `publish` step of the registry plugin (`registryStep`) and of every plugin after it, then every plugin's `success`. Plugins run in order and stop at the first failure, so a version missing from the registry means no plugin from the registry plugin on published it, while the ones before it may have.
 */
export function createTaggedCommitPublisher(context: {
  readonly repoRoot: string;
  readonly env: NodeJS.ProcessEnv;
  readonly log: (message: string) => void;
  readonly tagFormat: string;
  readonly branches: readonly BranchSpec[] | undefined;
  readonly plugins: ReadonlyMap<string, readonly ResolvedPublishPlugin[]>;
  /** Index into each package's `plugins` of its registry publish step; see `registryPublishStep`. */
  readonly registryStep: (pkg: WorkspacePackage) => number;
  readonly generateNotesConfig: Record<string, unknown>;
  /** The extra source paths of each package, so the regenerated notes list the same commits the release's own notes did. */
  readonly sources: PackageSourcePatterns;
}): TaggedCommitPublisher {
  const { repoRoot, env, log } = context;
  const checkouts = new Map<string, Promise<string>>();
  // Every checkout directory created, including one whose checkout or install then failed, so `close` removes them all.
  const directories: string[] = [];
  const moduleCache = new Map<string, LoadedReleasePlugin>();

  /** The root of a checkout of `commit`, created and installed the first time it is asked for. `pkg` is any package of the workspace, which locates the workspace root inside the checkout. */
  async function checkoutOf(commit: string, pkg: WorkspacePackage): Promise<string> {
    const existing = checkouts.get(commit);
    if (existing !== undefined) {
      return existing;
    }
    const created = (async () => {
      const directory = await mkdtemp(join(tmpdir(), `${packageName.replace(/[@/]/g, '-')}-recovery-`));
      directories.push(directory);
      await addDetachedWorktree(directory, commit, { cwd: repoRoot });
      log(`${packageName}: checked out ${commit} into ${directory}; installing it from its lockfile`);
      await installFrozenLockfile({ cwd: join(directory, workspacePrefix(pkg)), env });
      return directory;
    })();
    checkouts.set(commit, created);
    return created;
  }

  return {
    async publish({ pkg, release }: RecoveryCandidate) {
      const releaseContext = await captureReleaseContext(pkg, context);
      if (releaseContext === undefined) {
        throw new WorkspaceStateError(
          `semantic-release will not release ${pkg.name} from this checkout (its log above says why: not a release branch, a pull request build, or a branch behind its remote), so ${release.gitTag} cannot be republished from it either.`,
        );
      }
      if (releaseContext.lastRelease.gitTag !== release.gitTag) {
        throw new WorkspaceStateError(`semantic-release does not read ${release.gitTag} as ${pkg.name}'s last release on this branch, so which release to republish is ambiguous.`);
      }
      const repositoryUrl = releaseContext.options.repositoryUrl;
      if (repositoryUrl === undefined) {
        throw new ReleaseConfigurationError('Internal error: semantic-release did not resolve a repository URL before analyzeCommits ran.');
      }

      const commit = await commitOf(release.gitTag, { cwd: repoRoot });
      const checkout = await checkoutOf(commit, pkg);
      const cwd = join(checkout, pkg.repoRelativeDirectory);

      const tags = await releasedTags(pkg.name, context.tagFormat, { cwd: repoRoot });
      const previous = tags[tags.findIndex((tag) => tag.gitTag === release.gitTag) + 1];
      const lastRelease: LastRelease | Readonly<Record<string, never>> =
        previous === undefined
          ? {}
          : { version: previous.version, gitTag: previous.gitTag, gitHead: await commitOf(previous.gitTag, { cwd: repoRoot }), channels: [], name: previous.gitTag };
      const type = semver.diff(previous?.version ?? NO_PREVIOUS_VERSION, release.version);
      if (!isReleaseType(type)) {
        throw new WorkspaceStateError(`${release.gitTag} does not follow ${previous?.gitTag ?? 'no release'} as a release, so it cannot be republished as one.`);
      }
      const channel = channelOrNull(releaseContext.branch.channel);
      const nextRelease = { type, version: release.version, gitTag: release.gitTag, gitHead: commit, name: release.gitTag, channel };

      // Ends at the release commit's parent: the commit the release's own analysis ran on.
      const commits = await readCommits(`${previous === undefined ? '' : `${previous.gitTag}..`}${commit}^`, { cwd: repoRoot });
      let scopedCommits: readonly Commit[] = commits;
      const scoped = createScopedPlugins({
        pkg,
        analyzeCommitsConfig: {},
        generateNotesConfig: context.generateNotesConfig,
        bumps: { bumpsFor: () => [] },
        sources: mustGet(context.sources, pkg.name, 'package sources'),
        onCommitsResolved: (resolved) => {
          scopedCommits = resolved;
        },
      });
      const notes = await scoped.generateNotes({}, { ...releaseContext, cwd, commits, lastRelease, nextRelease, releases: [] });
      if (typeof notes !== 'string') {
        throw new ReleaseConfigurationError(`Internal error: no release notes were generated for ${release.gitTag}.`);
      }

      const plugins = mustGet(context.plugins, pkg.name, 'publish plugins');
      const registryStep = context.registryStep(pkg);
      const releases: unknown[] = [];
      const callContext = (): PluginCallContext => ({
        cwd,
        env: { ...env },
        stdout: process.stdout,
        stderr: process.stderr,
        logger: createPluginLogger(pkg.name, log),
        options: { repositoryUrl },
        branch: releaseContext.branch,
        commits: scopedCommits,
        releases,
        nextRelease: { ...nextRelease, notes },
      });

      const loaded = await Promise.all(plugins.map(async ([modulePath, pluginConfig]) => ({ plugin: await loadReleasePlugin(modulePath, moduleCache), pluginConfig })));
      for (const { plugin, pluginConfig } of loaded) {
        await plugin.verifyConditions?.(pluginConfig, callContext());
      }
      for (const { plugin, pluginConfig } of loaded.slice(registryStep)) {
        const result = await plugin.publish?.(pluginConfig, callContext());
        if (result !== false && result !== undefined) {
          releases.push(result);
        }
      }
      for (const { plugin, pluginConfig } of loaded) {
        await plugin.success?.(pluginConfig, callContext());
      }
    },

    async close() {
      for (const directory of directories.splice(0)) {
        await rm(directory, { recursive: true, force: true });
      }
      checkouts.clear();
      await pruneWorktrees({ cwd: repoRoot });
    },
  };
}

/** The workspace root's own path within the repository, `''` when `pnpm-workspace.yaml` sits at the repository's toplevel: the part of a package's repository-relative directory its workspace-relative one does not repeat. */
function workspacePrefix(pkg: WorkspacePackage): string {
  return pkg.repoRelativeDirectory.slice(0, pkg.repoRelativeDirectory.length - pkg.relativeDirectory.length);
}

/**
 * Runs semantic-release for `pkg` in dry-run mode with no publish plugins and an `analyzeCommits` step that records the context it is handed and releases nothing. That context is what every release of the package starts from: its branch and channel, its repository, and its last release. `undefined` when semantic-release stops before analysis, which it does wherever it would not release at all.
 */
async function captureReleaseContext(
  pkg: WorkspacePackage,
  options: { readonly tagFormat: string; readonly branches: readonly BranchSpec[] | undefined; readonly env: NodeJS.ProcessEnv },
): Promise<(AnalyzeCommitsContext & { cwd: string }) | undefined> {
  let captured: (AnalyzeCommitsContext & { cwd: string }) | undefined;
  const semanticReleaseOptions: Options = {
    tagFormat: formatTagForPackage(options.tagFormat, pkg.name),
    plugins: [],
    dryRun: true,
    async analyzeCommits(_pluginConfig: Record<string, unknown>, context: AnalyzeCommitsContext & { cwd: string }): Promise<false> {
      captured = context;
      return Promise.resolve(false);
    },
  };
  if (options.branches !== undefined) {
    semanticReleaseOptions.branches = options.branches;
  }
  await semanticRelease(semanticReleaseOptions, { cwd: pkg.directory, env: { ...options.env } });
  return captured;
}
